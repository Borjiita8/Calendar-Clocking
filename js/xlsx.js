// Cada celda puede ser: null, string, number o { v, s, f } donde
//   s = estilo ('header' | 'date' | 'time' | 'dur' | 'datetime' | 'bold' | 'boldDur' | 'num')
//   f = fórmula (opcional; v es el valor precalculado)

